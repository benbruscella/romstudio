import { hex } from '../core.js';
import { BRANCHES, branchTarget, type Instruction } from './mos6502.js';

export interface LiftedProgram {
  typescript: string;
  javascript: string;
  mappings: {
    address: number;
    generatedLine: number;
    bytes: number[];
    source?: Instruction['source'];
  }[];
  gaps: { address: number; kind: string; detail: string }[];
}
/** Compile each recovered instruction to a source-address case. Runtime dispatch is
 * over known source addresses, not an opcode decoder or external emulator. */
export function lift(
  instructions: Instruction[],
  options: { mutableOperands?: boolean } = {},
): LiftedProgram {
  const lines = [
    '// Generated by ROM Studio. Changes belong in the recipe or CPU backend.',
    '/** Instruction-level timing; cycle-by-cycle device bus timing is not implemented. */',
    'export function step(s) {',
    '  switch (s.pc) {',
  ];
  const mappings: LiftedProgram['mappings'] = [],
    gaps: LiftedProgram['gaps'] = [];
  for (const i of instructions) {
    mappings.push({
      address: i.address,
      generatedLine: lines.length + 1,
      bytes: i.bytes,
      ...(i.source ? { source: i.source } : {}),
    });
    const next = (i.address + i.size) & 65535;
    const body: string[] = [
      `s.guard(${i.address}, ${JSON.stringify(options.mutableOperands ? [i.opcode] : i.bytes)});`,
      's.beginInstruction();',
      `let next = ${next};`,
      'let extra = 0;',
    ];
    if (i.mnemonic === 'JSR') {
      // JSR fetches its high operand after the two return-address writes.
      body.push(
        `const low = s.read(${(i.address + 1) & 65535});`,
        's.idle(1);',
        `s.push(${(next - 1) >>> 8}); s.push(${(next - 1) & 255});`,
        `next = low | (s.read(${(i.address + 2) & 65535}) << 8);`,
        's.pc = next; s.finishInstruction(6); s.instructions++; return;',
      );
      lines.push(
        `    case ${i.address}: { // $${hex(i.address)} ${i.text}`,
        ...body.map((line) => `      ${line}`),
        '    }',
      );
      continue;
    }
    if (options.mutableOperands && i.size > 1) {
      body.push(
        `const operand = s.read(${(i.address + 1) & 65535})${i.size === 3 ? ` | (s.read(${(i.address + 2) & 65535}) << 8)` : ''};`,
      );
    } else if (i.size > 1) {
      body.push(`s.idle(${i.size - 1});`);
    }
    const operand = options.mutableOperands ? 'operand' : String(i.operand);
    let address = '',
      base = '';
    switch (i.mode) {
      case 'zp':
      case 'abs':
        address = operand;
        break;
      case 'zpx':
        address = `(${operand} + s.x) & 255`;
        break;
      case 'zpy':
        address = `(${operand} + s.y) & 255`;
        break;
      case 'abx':
      case 'aby':
        base = operand;
        address = `(base + s.${i.mode === 'abx' ? 'x' : 'y'}) & 65535`;
        break;
      case 'izx':
        address = `s.zpWord((${operand} + s.x) & 255)`;
        break;
      case 'izy':
        base = `s.zpWord(${operand})`;
        address = '(base + s.y) & 65535';
        break;
      case 'ind':
        address = operand;
        break;
    }
    if (['zpx', 'zpy', 'izx'].includes(i.mode)) {
      body.push('s.idle(1);');
    }
    if (base) {
      body.push(`const base = ${base};`);
    }
    if (address) {
      body.push(`const address = ${address};`);
    }
    if (i.pagePenalty) {
      body.push('extra += (base & 65280) !== (address & 65280) ? 1 : 0;');
    }
    if (['abx', 'aby', 'izy'].includes(i.mode) && i.mnemonic !== 'NOP') {
      if (['STA', 'STX', 'STY', 'INC', 'DEC', 'ASL', 'LSR', 'ROL', 'ROR'].includes(i.mnemonic)) {
        body.push('s.idle(1);');
      } else {
        body.push('if (extra) s.idle(1);');
      }
    }
    if (['PHA', 'PHP'].includes(i.mnemonic)) {
      body.push('s.idle(1);');
    }
    if (['PLA', 'PLP', 'RTS', 'RTI'].includes(i.mnemonic)) {
      body.push('s.idle(2);');
    }
    const value = i.mode === 'imm' ? operand : 's.read(address)';
    const branch = BRANCHES[i.mnemonic];
    if (branch) {
      const target = branchTarget(i.address, i.operand);
      body.push(
        options.mutableOperands
          ? `if (${branch.set ? '!!' : '!'}(s.p & ${branch.flag})) { const target = (next + (operand < 128 ? operand : operand - 256)) & 65535; extra += 1 + ((next & 65280) !== (target & 65280) ? 1 : 0); next = target; }`
          : `if (${branch.set ? '!!' : '!'}(s.p & ${branch.flag})) { next = ${target}; extra += ${1 + ((next & 0xff00) !== (target & 0xff00) ? 1 : 0)}; }`,
      );
    } else {
      switch (i.mnemonic) {
        case 'LDA':
        case 'LDX':
        case 'LDY':
          body.push(`s.${i.mnemonic[2]!.toLowerCase()} = s.nz(${value});`);
          break;
        case 'STA':
        case 'STX':
        case 'STY':
          body.push(`s.write(address, s.${i.mnemonic[2]!.toLowerCase()});`);
          break;
        case 'TAX':
          body.push('s.x = s.nz(s.a);');
          break;
        case 'TAY':
          body.push('s.y = s.nz(s.a);');
          break;
        case 'TXA':
          body.push('s.a = s.nz(s.x);');
          break;
        case 'TYA':
          body.push('s.a = s.nz(s.y);');
          break;
        case 'TSX':
          body.push('s.x = s.nz(s.sp);');
          break;
        case 'TXS':
          body.push('s.sp = s.x;');
          break;
        case 'INX':
          body.push('s.x = s.nz(s.x + 1);');
          break;
        case 'INY':
          body.push('s.y = s.nz(s.y + 1);');
          break;
        case 'DEX':
          body.push('s.x = s.nz(s.x - 1);');
          break;
        case 'DEY':
          body.push('s.y = s.nz(s.y - 1);');
          break;
        case 'INC':
        case 'DEC':
          body.push(
            `const old = s.read(address); s.write(address, old); s.write(address, s.nz(old ${i.mnemonic === 'INC' ? '+' : '-'} 1));`,
          );
          break;
        case 'AND':
          body.push(`s.a = s.nz(s.a & ${value});`);
          break;
        case 'ORA':
          body.push(`s.a = s.nz(s.a | ${value});`);
          break;
        case 'EOR':
          body.push(`s.a = s.nz(s.a ^ ${value});`);
          break;
        case 'ADC':
          body.push(`s.adc(${value});`);
          break;
        case 'SBC':
          body.push(`s.sbc(${value});`);
          break;
        case 'CMP':
        case 'CPX':
        case 'CPY':
          body.push(
            `s.compare(s.${i.mnemonic === 'CMP' ? 'a' : i.mnemonic[2]!.toLowerCase()}, ${value});`,
          );
          break;
        case 'BIT':
          body.push(
            `const value = ${value}; s.flag(2, !(s.a & value)); s.flag(128, !!(value & 128)); s.flag(64, !!(value & 64));`,
          );
          break;
        case 'ASL':
        case 'LSR':
        case 'ROL':
        case 'ROR': {
          body.push(
            `const old = ${i.mode === 'acc' ? 's.a' : 's.read(address)'}; const carry = s.p & 1;`,
          );
          const left = i.mnemonic === 'ASL' || i.mnemonic === 'ROL';
          body.push(`s.flag(1, !!(old & ${left ? 128 : 1}));`);
          const expression =
            i.mnemonic === 'ASL'
              ? 'old << 1'
              : i.mnemonic === 'LSR'
                ? 'old >>> 1'
                : i.mnemonic === 'ROL'
                  ? '(old << 1) | carry'
                  : '(old >>> 1) | (carry << 7)';
          if (i.mode === 'acc') {
            body.push(`s.a = s.nz(${expression});`);
          } else {
            body.push(`s.write(address, old); s.write(address, s.nz(${expression}));`);
          }
          break;
        }
        case 'CLC':
        case 'SEC':
          body.push(`s.flag(1, ${i.mnemonic === 'SEC'});`);
          break;
        case 'CLI':
        case 'SEI':
          body.push(`s.flag(4, ${i.mnemonic === 'SEI'});`);
          break;
        case 'CLD':
        case 'SED':
          body.push(`s.flag(8, ${i.mnemonic === 'SED'});`);
          break;
        case 'CLV':
          body.push('s.flag(64, false);');
          break;
        case 'PHA':
          body.push('s.push(s.a);');
          break;
        case 'PHP':
          body.push('s.push(s.p | 48);');
          break;
        case 'PLA':
          body.push('s.a = s.nz(s.pop());');
          break;
        case 'PLP':
          body.push('s.p = (s.pop() | 32) & 239;');
          break;
        case 'JMP':
          body.push(
            i.mode === 'ind'
              ? 'next = s.read(address) | (s.read((address & 65280) | ((address + 1) & 255)) << 8);'
              : `next = ${operand};`,
          );
          break;
        case 'JSR':
          body.push(`s.push(${(next - 1) >>> 8}); s.push(${(next - 1) & 255}); next = ${operand};`);
          break;
        case 'RTS':
          body.push('next = ((s.pop() | (s.pop() << 8)) + 1) & 65535;');
          break;
        case 'RTI':
          body.push('s.p = (s.pop() | 32) & 239; next = s.pop() | (s.pop() << 8);');
          break;
        case 'NOP':
          if (i.mode === 'abx') {
            body.push('if (extra) s.read((base & 65280) | (address & 255));');
            body.push('s.read(address);');
          }
          break;
        default:
          gaps.push({
            address: i.address,
            kind: 'unsupported-lift',
            detail: `${i.mnemonic} requires interrupt service support.`,
          });
          body.push(
            `s.gap('interrupt', '${i.mnemonic} needs an interrupt-capable system adapter.');`,
          );
      }
    }
    body.push(`s.pc = next; s.finishInstruction(${i.cycles} + extra); s.instructions++; return;`);
    lines.push(
      `    case ${i.address}: { // $${hex(i.address)} ${i.text}`,
      ...body.map((line) => `      ${line}`),
      '    }',
    );
  }
  lines.push(
    "    default: s.gap('unresolved-target', 'No lifted instruction at the current source address.');",
    '  }',
    '}',
    '',
  );
  const javascript = lines.join('\n');
  // Both artifacts use the same semantics. The JS output is a static module with no eval.
  const typescript = `import type { Machine } from './runtime.js';\n${javascript.replace('step(s)', 'step(s: Machine)')}`;
  for (const mapping of mappings) {
    mapping.generatedLine++;
  }
  return { typescript, javascript, mappings, gaps };
}
