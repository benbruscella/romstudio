import type { Instruction } from './mos6502.js';
import { lift } from './lift.js';
import { posix } from 'node:path';

export interface GeneratedModule {
  javascript: string;
  typescript: string;
}
export interface GeneratedProgram extends GeneratedModule {
  shapes: Pick<Instruction, 'address' | 'opcode' | 'size' | 'mnemonic' | 'mode'>[];
  modules?: Record<string, GeneratedModule>;
}

/** Static source-address dispatch for reviewed self-modifying operand fields.
 * Recovered opcode/address pairs determine instruction shapes at build time.
 * Operands remain RAM data; an unobserved opcode or address stops explicitly.
 * No decoder, eval or dynamic compiler is shipped in the generated module. */
export function liftObservedShapes(
  instructions: Instruction[],
  options: { runtimeImport?: string } = {},
): GeneratedProgram {
  const shapes = new Map<string, Instruction>();
  for (const instruction of instructions) {
    shapes.set(`${instruction.address}:${instruction.opcode}`, instruction);
  }
  const ordered = [...shapes.values()].sort((a, b) => a.address - b.address || a.opcode - b.opcode);
  const functions: string[] = [],
    cases = new Map<number, string[]>();
  for (const instruction of ordered) {
    const name = `at_${instruction.address.toString(16)}_${instruction.opcode.toString(16)}`;
    functions.push(
      lift([instruction], { mutableOperands: true }).javascript.replace(
        'export function step(s)',
        `function ${name}(s)`,
      ),
    );
    const alternatives = cases.get(instruction.address) ?? [];
    alternatives.push(`[${instruction.opcode}, ${name}]`);
    cases.set(instruction.address, alternatives);
  }
  // A small dispatcher stays optimisable as coverage grows. A multi-thousand
  // case function exceeded the JS engine's optimisation budget on Nebulus.
  // These are explicit source-address/guarded-function entries, not an opcode
  // interpreter: no operation is decoded or generated at runtime.
  const dispatcher = [
    'const program = new Map([',
    ...[...cases].map(
      ([address, alternatives]) => `[${address}, new Map([${alternatives.join(', ')}])],`,
    ),
    ']);',
    'export function step(s) {',
    'const variants = program.get(s.pc);',
    'const operation = variants?.get(s.bus.peek(s.pc));',
    'if (operation) return operation(s);',
    "s.gap('unobserved-shape', 'This source address/opcode was not recovered for the browser slice.');",
    '}',
  ];
  const javascript = [...functions, ...dispatcher].join('\n');
  const typescript =
    `import type { Machine } from '${options.runtimeImport ?? './runtime/mos6502.js'}';\n` +
    javascript.replace(/function (at_[a-f0-9_]+|step)\(s\)/g, 'function $1(s: Machine)');
  return {
    javascript,
    typescript,
    shapes: ordered.map(({ address, opcode, size, mnemonic, mode }) => ({
      address,
      opcode,
      size,
      mnemonic,
      mode,
    })),
  };
}

/** Large programs use one module per 4 KiB source-address page. Splitting
 * changes delivery, not CPU semantics: every operation is still selected from
 * statically emitted address/opcode pairs and guarded before execution. */
export function liftAddressPages(
  instructions: Instruction[],
  options: { runtimeImport?: string; pageThreshold?: number } = {},
): GeneratedProgram {
  const unique = new Map(instructions.map((item) => [`${item.address}:${item.opcode}`, item]));
  if (unique.size <= (options.pageThreshold ?? 8192)) {
    return liftObservedShapes([...unique.values()], options);
  }
  const groups = new Map<number, Instruction[]>();
  for (const item of unique.values()) {
    const page = item.address >>> 12;
    const group = groups.get(page) ?? [];
    group.push(item);
    groups.set(page, group);
  }
  const modules: Record<string, GeneratedModule> = {};
  const imports: string[] = [];
  const entries: string[] = [];
  const shapes: GeneratedProgram['shapes'] = [];
  for (const [page, items] of [...groups].sort(([a], [b]) => a - b)) {
    const name = (page << 12).toString(16).padStart(4, '0');
    const generated = liftObservedShapes(items, {
      runtimeImport: posix.join('..', options.runtimeImport ?? './runtime/mos6502.js'),
    });
    modules[`pages/${name}`] = generated;
    imports.push(`import { step as page_${name} } from './pages/${name}.js';`);
    entries.push(`[${page}, page_${name}]`);
    shapes.push(...generated.shapes);
  }
  const javascript = [
    '// Generated by ROM Studio. Instruction bodies live in source-address pages.',
    ...imports,
    `const pages = new Map([${entries.join(',')}]);`,
    'export function step(s) {',
    'const page = pages.get(s.pc >>> 12);',
    'if (page) return page(s);',
    "s.gap('unobserved-shape', 'This source-address page was not included in the static program.');",
    '}',
  ].join('\n');
  return {
    javascript,
    typescript:
      `import type { Machine } from '${options.runtimeImport ?? './runtime/mos6502.js'}';\n` +
      javascript.replace('function step(s)', 'function step(s: Machine)'),
    shapes,
    modules,
  };
}

export function programFiles(
  program: Pick<GeneratedProgram, 'javascript' | 'modules'> & { typescript?: string },
  includeTypeScript = false,
): Record<string, string> {
  const files: Record<string, string> = { 'program.js': program.javascript };
  if (includeTypeScript && program.typescript !== undefined) {
    files['program.ts'] = program.typescript;
  }
  for (const [name, module] of Object.entries(program.modules ?? {})) {
    files[name + '.js'] = module.javascript;
    if (includeTypeScript) {
      files[name + '.ts'] = module.typescript;
    }
  }
  return files;
}
