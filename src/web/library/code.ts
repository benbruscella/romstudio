import type { SourceObservation } from '../../contracts.js';

/** Generated functions have stable source-address names. Never eval source. */
export function instructionTypeScript(source: string, address: number, opcode: number): string {
  const name = `function at_${address.toString(16)}_${opcode.toString(16)}(`;
  const start = source.indexOf(name);
  if (start < 0) {
    return 'No generated function was found for this observation.';
  }
  const nextFunction = source.indexOf('\nfunction at_', start + name.length);
  const dispatcher = source.indexOf('\nconst program =', start + name.length);
  const nextHeader = source.indexOf('\n// Generated by', start + name.length);
  const ends = [nextFunction, dispatcher, nextHeader].filter((position) => position >= 0);
  return source.slice(start, ends.length ? Math.min(...ends) : undefined).trim();
}

/** Large games keep full observation provenance in bounded JSON pages. */
export async function loadCodeObservations(directory: string, request: typeof fetch = fetch) {
  const mappingResponse = await request(directory + 'observed-source.json');
  if (!mappingResponse.ok) {
    throw new Error('Rebuild this game to include its code observations.');
  }
  const { mappings, scope, parts } = (await mappingResponse.json()) as {
    mappings: SourceObservation[];
    scope?: string;
    parts?: string[];
  };
  if (
    !Array.isArray(mappings) ||
    (parts !== undefined &&
      (!Array.isArray(parts) ||
        parts.length > 4096 ||
        new Set(parts).size !== parts.length ||
        parts.some((part) => !/^observations\/[0-9a-f]{4}\.json$/.test(part))))
  ) {
    throw new Error('Invalid code observation index.');
  }
  const pages = await Promise.all(
    (parts ?? []).map(async (part) => {
      const response = await request(directory + part);
      if (!response.ok) {
        throw new Error('A code observation page is unavailable.');
      }
      const values: unknown = await response.json();
      if (!Array.isArray(values)) {
        throw new Error('Invalid code observation page.');
      }
      return values as SourceObservation[];
    }),
  );
  return { mappings: [...mappings, ...pages.flat()], scope };
}

export async function codeExplorer(directory: string): Promise<HTMLElement> {
  const { mappings, scope } = await loadCodeObservations(directory);
  const root = document.createElement('section');
  const sources = new Map<string, Promise<string>>();
  let selection = 0;
  root.className = 'code-explorer';
  const title = document.createElement('h2');
  title.textContent = 'Original instruction → TypeScript';
  const note = document.createElement('p');
  note.textContent =
    'Explore observed instruction bytes and their precise generated translation. Named game explanations are in the chapters. Mutable operands can change; this shows the first observed variant, not a live machine or complete bank/epoch trace.';
  if (scope) {
    note.textContent = scope + ' ' + note.textContent;
  }
  const label = document.createElement('label');
  label.textContent = 'Source address (hex) ';
  const input = document.createElement('input');
  input.placeholder = '$' + (mappings[0]?.address ?? 0).toString(16).toUpperCase().padStart(4, '0');
  input.setAttribute('aria-label', 'Source address in hexadecimal');
  label.append(input);
  const layout = document.createElement('div');
  layout.className = 'code-layout';
  const list = document.createElement('div');
  list.className = 'instruction-list';
  list.setAttribute('aria-label', 'Observed assembly');
  const detail = document.createElement('div'),
    original = document.createElement('pre'),
    generated = document.createElement('pre'),
    metadata = document.createElement('p');
  detail.append(metadata, original, generated);
  layout.append(list, detail);
  root.append(title, note, label, layout);
  const hex = (value: number, width = 4) => value.toString(16).toUpperCase().padStart(width, '0');
  const show = async (item: SourceObservation) => {
    const version = ++selection;
    metadata.textContent = `$${hex(item.address)} · first observed at recovery instruction ${item.firstInstruction.toLocaleString()} · ${item.visits.toLocaleString()} visits across the declared traces`;
    if (Array.isArray(item.provenance?.traces)) {
      metadata.textContent += ' · ' + item.provenance.traces.length + ' declared trace(s)';
      metadata.title = item.provenance.traces.join('\n');
    } else {
      metadata.title = '';
    }
    original.textContent = `${hex(item.address)}  ${item.bytes.map((byte) => hex(byte, 2)).join(' ')}  ${item.assembly}`;
    generated.textContent = 'Loading generated source…';
    for (const button of Array.from(list.querySelectorAll('button'))) {
      button.setAttribute(
        'aria-pressed',
        String(
          button.dataset.address === String(item.address) &&
            button.dataset.opcode === String(item.opcode),
        ),
      );
    }
    try {
      const file = item.sourceFile ?? 'program.ts';
      if (!/^(?:program\.ts|pages\/[0-9a-f]{4}(?:[0-9a-f]{4})?\.ts)$/.test(file)) {
        throw new Error('Invalid source page.');
      }
      if (!sources.has(file)) {
        sources.set(
          file,
          fetch(directory + file).then(async (response) => {
            if (!response.ok) {
              throw new Error('The generated source page is unavailable.');
            }
            return response.text();
          }),
        );
      }
      const source = await sources.get(file)!;
      if (version === selection) {
        generated.textContent = instructionTypeScript(source, item.address, item.opcode);
      }
    } catch (error) {
      if (version === selection) {
        generated.textContent = String(error);
      }
    }
  };
  const render = () => {
    const query = input.value
      .trim()
      .replace(/^(?:\$|0x)/i, '')
      .toLowerCase();
    const filtered = query
      ? mappings.filter((item) => item.address.toString(16).startsWith(query))
      : mappings;
    list.replaceChildren();
    for (const item of filtered.slice(0, 300)) {
      const button = document.createElement('button');
      button.textContent = `${hex(item.address)}  ${item.assembly}`;
      button.dataset.address = String(item.address);
      button.dataset.opcode = String(item.opcode);
      button.addEventListener('click', () => {
        void show(item);
      });
      list.append(button);
    }
    if (filtered[0]) {
      void show(filtered[0]);
    } else {
      selection++;
      metadata.textContent = 'No observed instruction matches this address.';
      original.textContent = '';
      generated.textContent = '';
    }
  };
  input.addEventListener('input', render);
  render();
  return root;
}
